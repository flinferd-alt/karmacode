// Функция для генерации описания на основе числового кода
export function getKarmaData(code: string): KarmaCodeData {
  // Проверяем, есть ли точное совпадение
  if (karmaCodes[code]) {
    return karmaCodes[code];
  }
  
  // Если код трёхзначный, берём первую цифру как основу
  if (code.length === 3) {
    const baseCode = code[0].repeat(3);
    if (karmaCodes[baseCode]) {
      return {
        ...karmaCodes[baseCode],
        code: code,
        title: karmaCodes[baseCode].title,
        subtitle: `Уникальная вариация — ${code}`
      };
    }
  }
  
  // Генерируем данные на основе числовой суммы
  const sum = code.split('').reduce((acc, digit) => acc + parseInt(digit || '0'), 0);
  const baseIndex = (sum % 9) + 1;
  const baseCode = String(baseIndex).repeat(3);
  
  if (karmaCodes[baseCode]) {
    return {
      ...karmaCodes[baseCode],
      code: code,
      title: karmaCodes[baseCode].title,
      subtitle: `Персональная вибрация — ${code}`
    };
  }
  
  // Фоллбэк
  return karmaCodes["111"];
}
